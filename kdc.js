// 분류 번호: 정해진 자리까지만 채우고 나머지는 0 (예: 8 → 800, 81 → 810, 813)
function kdcCode({ kdcMain, kdcDiv, litForm }) {
  if (!kdcMain) return '';
  const third = kdcMain === LITERATURE && kdcDiv && kdcDiv !== '9' && litForm ? litForm : '0';
  return kdcMain + (kdcDiv || '0') + third;
}

// 화면 표시용 이름 (예: "한국문학 · 소설", "문학 · 시", "물리학")
function kdcName({ kdcMain, kdcDiv, litForm }) {
  if (!kdcMain) return '';
  const main = KDC[kdcMain];
  const base = kdcDiv ? main.divs[kdcDiv] : main.name;
  const form = kdcMain === LITERATURE && litForm ? LIT_FORMS[litForm] : '';
  return form ? `${base} · ${form}` : base;
}
